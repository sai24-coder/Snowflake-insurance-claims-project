
USE DATABASE INSURANCE_DB;
USE SCHEMA CURATED;

--1. RECORD LEVEL ERROR TABLE
--Stores records rejected due to data/business validation


CREATE OR REPLACE TABLE ERROR_RECORDS(
    ERROR_ID NUMBER AUTOINCREMENT,
    BATCH_ID VARCHAR(100),
    SOURCE_TABLE VARCHAR(100),
    RECORD_KEY VARCHAR(100),
    ERROR_TYPE VARCHAR(100),
    ERROR_MESSAGE VARCHAR(500),
    RAW_DATA VARIANT,
    ERROR_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    STATUS VARCHAR(30) DEFAULT 'FAILED',
    RETRY_COUNT NUMBER DEFAULT 0,
    REPROCESS_AT TIMESTAMP_NTZ
);




-- 2. PROCESS /TECHNICAL ERRORS
-- Stores stored procedure, task and pipeline failures

CREATE OR REPLACE TABLE PROCESS_ERROR_LOG
(
    ERROR_ID NUMBER AUTOINCREMENT,
    PROCESS_NAME VARCHAR(200),
    ERROR_CODE VARCHAR(100),
    ERROR_MESSAGE VARCHAR(1000),
    ERROR_TIMESTAMP TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    STATUS VARCHAR(30) DEFAULT 'FAILED',
);