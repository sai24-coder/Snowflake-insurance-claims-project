USE DATABASE INSURANCE_DB;
USE SCHEMA AUDIT;
CREATE OR REPLACE TABLE PIPELINE_AUDIT_LOG(
    PIPELINE_NAME STRING,
    LOAD_STATUS STRING,
    RECORD_COUNT NUMBER,
    START_TIME TIMESTAMP,
    END_TIME TIMESTAMP,
    COMMENTS STRING
);

-------------------------------------------------------------------------------------------------------------------

CREATE OR REPLACE PROCEDURE SP_AUDIT_LOGGING
(
    PIPELINE_NAME STRING,
    LOAD_STATUS STRING,
    RECORD_COUNT NUMBER,
    COMMENTS STRING

)
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN

INSERT INTO AUDIT.PIPELINE_AUDIT_LOG
(
    PIPELINE_NAME,
    LOAD_STATUS,
    RECORD_COUNT,
    START_TIME,
    END_TIME,
    COMMENTS
)
VALUES
(
    :PIPELINE_NAME,
    :LOAD_STATUS,
    :RECORD_COUNT,
    CURRENT_TIMESTAMP(),
    CURRENT_TIMESTAMP(),
    :COMMENTS
);

RETURN 'Audit log entry created successfully.';
END;
$$;