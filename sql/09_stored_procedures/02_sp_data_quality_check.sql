CREATE OR REPLACE PROCEDURE SP_DATA_QUALITY_CHECK()
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    NULL_COUNT NUMBER;
BEGIN

    SELECT COUNT(*) INTO :NULL_COUNT
    FROM INSURANCE_ODS.CUSTOMER_ODS
    WHERE CUSTOMER_ID IS NULL;

    IF (NULL_COUNT >0) THEN
        RETURN 'FAILED';
    END IF;
    
    RETURN 'SUCCESS';

END;
$$;