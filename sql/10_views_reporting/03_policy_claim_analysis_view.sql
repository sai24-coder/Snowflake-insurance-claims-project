CREATE OR REPLACE VIEW POLICY_CLAIM_ANALYSIS_VW AS
SELECT
    P.POLICY_ID,
    P.POLICY_TYPE,
    COUNT(C.CLAIM_ID) AS TOTAL_CLAIMS,
    SUM(C.CLAIM_AMOUNT) AS TOTAL_CLAIM_AMOUNT,
    AVG(C.CLAIM_AMOUNT) AS AVERAGE_CLAIM_AMOUNT
FROM INSURANCE_CURATED.CLAIM_FACT C
INNER JOIN INSURANCE_CURATED.POLICY_DIM P
ON C.POLICY_KEY = P.POLICY_KEY
GROUP BY P.POLICY_ID, P.POLICY_TYPE;