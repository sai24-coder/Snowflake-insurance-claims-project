USE DATABASE INSURANCE_DB;
USE SCHEMA CURATED;


CREATE OR REPLACE VIEW CLAIM_SUMMARY_VW AS
SELECT
    C.CLAIM_ID,
    CU.CUSTOMER_ID,
    CU.FIRST_NAME,
    CU.LAST_NAME,
    P.POLICY_ID,
    P.POLICY_TYPE,
    C.CLAIM_DATE,
    C.CLAIM_AMOUNT,
    C.CLAIM_STATUS
FROM INSURANCE_CURATED.CLAIM_FACT C
INNER JOIN INSURANCE_CURATED.CUSTOMER_DIM CU
ON C.CUSTOMER_KEY = CU.CUSTOMER_KEY
INNER JOIN INSURANCE_CURATED.POLICY_DIM P
ON C.POLICY_KEY = P.POLICY_KEY
WHERE CU.CURRENT_FLAG = 'Y';

